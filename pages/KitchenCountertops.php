                    <h3>Do granite countertops need to be sealed? How often?</h3>
                    <p>Yes. <strong>Granite is a naturally porous stone</strong> and should be sealed once a year to maintain stain resistance. We apply the first coat of professional-grade penetrating sealant during installation at no extra charge. After that, we offer affordable <strong>annual sealing service visits</strong> — or we can provide DIY sealant and instructions if you prefer to do it yourself.</p>
                    <p><strong>Note:</strong> Quartz (engineered stone) is nonporous and <strong>never needs sealing</strong>. Marble and quartzite should be sealed every 6–12 months depending on use.</p>
                </div>

                <div class="faq-item">
