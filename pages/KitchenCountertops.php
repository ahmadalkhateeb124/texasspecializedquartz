                    </li>
                    <li>
                        <h4>Seam &amp; Joint Restoration</h4>
                        <p>Countertop seams can separate, discolor, or accumulate debris over time. We remove old epoxy, reclean the joint, and re-fill with fresh color-matched adhesive — restoring a tight, clean, and waterproof seam.</p>
