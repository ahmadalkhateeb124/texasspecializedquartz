                        <p>Over time, daily use can dull polished stone and leave micro-scratches invisible to the eye but visible in reflected light. Our deep cleaning and honing service strips buildup, removes light etching, and restores the original mirror-like polish to your granite, marble, or quartz countertops.</p>
                    </li>
                    <li>
                        <h4>Chip, Crack &amp; Scratch Repair</h4>
